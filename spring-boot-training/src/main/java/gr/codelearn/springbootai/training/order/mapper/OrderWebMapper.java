package gr.codelearn.springbootai.training.order.mapper;

import gr.codelearn.springbootai.training.order.Address;
import gr.codelearn.springbootai.training.order.Order;
import gr.codelearn.springbootai.training.order.OrderItem;
import gr.codelearn.springbootai.training.order.dto.AddressResponse;
import gr.codelearn.springbootai.training.order.dto.OrderDetailResponse;
import gr.codelearn.springbootai.training.order.dto.OrderLineResponse;
import gr.codelearn.springbootai.training.order.dto.PlaceOrderRequest;
import gr.codelearn.springbootai.training.order.internal.OrderConfirmation;
import gr.codelearn.springbootai.training.order.internal.PlaceOrderCommand;

import org.mapstruct.Mapper;
import org.mapstruct.Mapping;

import java.util.List;

/**
 * Bridges the order web contract and the internal order types (U4.4, replacing the U4.1 hand-written class of the same name), generated by
 * MapStruct from this {@code @Mapper} interface (no hand-written implementation - {@code componentModel = "spring"} makes the generated
 * {@code OrderWebMapperImpl} a {@code @Component}). Every call site ({@code OrderController}, {@code OrderService}) is unchanged, since the
 * field/parameter type was always this interface's name.
 *
 * <p><b>{@link #toCommand} needs no {@code @Mapping} at all.</b> {@link PlaceOrderCommand}'s components ({@code orderNumber},
 * {@code customerEmail}, {@code shippingAddress}, {@code lines}) match {@link PlaceOrderRequest}'s by name, so MapStruct auto-generates
 * both the nested record conversion ({@code AddressRequest -> } {@link Address}, identical component names) and the collection conversion
 * ({@code List<OrderLineRequest> -> List<PlaceOrderCommand.Line>}, identical component names) - the cleanest example in this unit of
 * "nested + collection mapping" needing zero configuration.
 *
 * <p><b>{@link #toResponse(OrderConfirmation)} stays a {@code default} method.</b> {@link OrderConfirmation} carries no customer email,
 * placement time, address, or line detail, so those four {@link OrderDetailResponse} fields are literal {@code null}/{@code List.of()} -
 * not sourced from anything MapStruct could map. Forcing that through {@code @Mapping(constant = ...)} four times would read worse than the
 * plain constructor call it replaces. Safe, because every endpoint that calls this ({@code placeOrder}, {@code listOrders},
 * {@code updateStatus}) is {@code @JsonView(Views.Summary.class)} and never serializes those fields.
 *
 * <p><b>{@link #toDetailResponse} must run inside a transaction</b> while {@code order.getItems()} and each item's {@code getProduct()}
 * are
 * still attached - {@code OrderService.getOrderDetail} calls it before its {@code readOnly} transaction returns, same requirement as the
 * U4.1/U4.3 hand-written version. {@code lines} reuses {@link #toResponse(OrderItem)} for the
 * {@code Set<OrderItem> -> List<OrderLineResponse>} collection mapping; {@code shippingAddress} reuses {@link #toResponse(Address)} for the
 * nested conversion - both auto-selected by MapStruct on return type, the same mechanism {@link #toCommand} uses implicitly.
 */
@Mapper(componentModel = "spring")
public interface OrderWebMapper {

	PlaceOrderCommand toCommand(PlaceOrderRequest request);

	default OrderDetailResponse toResponse(final OrderConfirmation confirmation) {
		return new OrderDetailResponse(
				confirmation.orderNumber(), confirmation.status(), confirmation.total(), confirmation.lineCount(), null, null, null,
				List.of());
	}

	@Mapping(target = "total", source = "totalAmount")
	@Mapping(target = "lineCount", expression = "java(order.getItems().size())")
	@Mapping(target = "customerEmail", source = "customer.email")
	@Mapping(target = "lines", source = "items")
	OrderDetailResponse toDetailResponse(Order order);

	AddressResponse toResponse(Address address);

	/**
	 * {@code lineTotal} is {@code unitPrice * quantity}; {@link OrderItem#lineTotal()} carries the same calculation but is package-private
	 * in {@code order}, unreachable from here (CLAUDE.md: cross-feature/-package access goes through public API, never an internal
	 * method),
	 * so the multiplication is restated as a MapStruct expression instead.
	 */
	@Mapping(target = "sku", source = "product.sku")
	@Mapping(target = "productName", source = "product.name")
	@Mapping(target = "lineTotal", expression = "java(item.getUnitPrice().multiply(java.math.BigDecimal.valueOf(item.getQuantity())))")
	OrderLineResponse toResponse(OrderItem item);
}