package gr.codelearn.springbootai.training.catalog.mapper;

import gr.codelearn.springbootai.training.catalog.Category;
import gr.codelearn.springbootai.training.catalog.Product;
import gr.codelearn.springbootai.training.catalog.dto.CategoryRequest;
import gr.codelearn.springbootai.training.catalog.dto.CategoryResponse;
import gr.codelearn.springbootai.training.catalog.dto.ProductPatchRequest;
import gr.codelearn.springbootai.training.catalog.dto.ProductRequest;
import gr.codelearn.springbootai.training.catalog.dto.ProductResponse;

import org.mapstruct.BeanMapping;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;
import org.mapstruct.NullValuePropertyMappingStrategy;

import org.springframework.data.domain.Page;

/**
 * Entity &lt;-&gt; DTO mapping for the catalog web layer (U4.4), generated by MapStruct from this {@code @Mapper} interface (no
 * hand-written implementation - {@code componentModel = "spring"} makes the generated {@code CatalogWebMapperImpl} a {@code @Component}).
 * Replaces the U4.1 hand-written class of the same name; every call site (all inside {@link CatalogService}) is unchanged, since the
 * field/parameter type was always this interface's name.
 *
 * <p>Called only from {@code CatalogService}, inside its {@code readOnly}/read-write transaction, so reading the LAZY
 * {@code product.category} in {@link #toResponse(Product)} is safe. A filtered page of products still triggers one category select per row
 * (the classic N+1); it is bounded by the page size and the fix (a fetch graph on the query) is U3.3 material, left out here.
 *
 * <p><b>Two things MapStruct cannot generate, left as {@code default} methods:</b> {@link #toResponsePage} has no {@code Page} support to
 * hook into (it is not a bean with matching properties, just a wrapper), so the "{@code Page<Entity>} -&gt; {@code Page<Response>} helper"
 * the unit asks for stays one line of hand-written delegation to {@link #toResponse(Product)}.
 *
 * <p><b>{@code category} is ignored on every update method, not auto-mapped.</b> {@link ProductRequest#categoryName()} /
 * {@link ProductPatchRequest#categoryName()} are {@code String}s (the category's business key on the wire); {@link Product#getCategory()}
 * is a {@link Category} entity. MapStruct maps by matching <i>types</i>, not just names, so there is no automatic
 * {@code String -> Category} conversion to generate - resolving the name against {@code CategoryRepository} needs a query, which a mapper
 * has no business doing (CLAUDE.md: services orchestrate, mappers only shape data). {@code CatalogService} still does that lookup and calls
 * {@code product.setCategory(...)} itself, right after the mapper writes everything else.
 *
 * <p><b>{@code sku} / {@code name} need no {@code ignore}.</b> {@link Product#getSku()} and {@link Category#getName()} are business keys
 * with no setter (CLAUDE.md: "no setter... equals/hashCode stay stable"); MapStruct only ever writes to a property that has one, so an
 * update method simply never touches them - nothing to ignore.
 */
@Mapper(componentModel = "spring")
public interface CatalogWebMapper {

	@Mapping(target = "categoryName", source = "category.name")
	ProductResponse toResponse(Product product);

	CategoryResponse toResponse(Category category);

	default Page<ProductResponse> toResponsePage(final Page<Product> page) {
		return page.map(this::toResponse);
	}

	/**
	 * Applies every field of {@code request} onto {@code product} for {@code PUT} (replace) - {@code name}, {@code description},
	 * {@code price} are written; {@code category} is resolved and set by the caller (see class Javadoc).
	 */
	@Mapping(target = "category", ignore = true)
	void updateEntityFromRequest(ProductRequest request, @MappingTarget Product product);

	/**
	 * Applies only the non-{@code null} fields of {@code request} onto {@code product} for {@code PATCH}.
	 * {@code nullValuePropertyMappingStrategy = IGNORE} makes MapStruct generate the same "skip if {@code null}" branch
	 * {@code CatalogService.patchProduct} used to write by hand, once per field.
	 */
	@BeanMapping(nullValuePropertyMappingStrategy = NullValuePropertyMappingStrategy.IGNORE)
	@Mapping(target = "category", ignore = true)
	void patchEntityFromRequest(ProductPatchRequest request, @MappingTarget Product product);

	/**
	 * Applies {@code request} onto {@code category} for {@code PUT} (replace). Only {@link Category#setDescription} exists, so this writes
	 * exactly one field - {@code name} has no setter (see class Javadoc) and the caller never overrides it either, since it is the path
	 * variable, not the body, that identifies which category to replace.
	 */
	void updateEntityFromRequest(CategoryRequest request, @MappingTarget Category category);
}